    philosophy_str = "\n".join(f"  - {p}" for p in knowledge["philosophy"])
    challenges_str = "\n".join(f"  - {c}" for c in knowledge["challenges"])
    events_str = "\n".join(f"  - {e}" for e in knowledge["life_events"])

