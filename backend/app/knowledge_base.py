def build_summon_prompt(character_name: str, poi_name: str) -> str:
    """构建召唤阶段的用户提示词"""
    return f"""现代后生通过地理时空裂缝与你产生了一次真正的命运相遇。你现在位于{poi_name}。
请生成一段开场白，包含三个要素：
1. 时间感（千年已过）
2. 地点感（当前{poi_name}的空间感受）
3. 个人感（后生你终于来了）

紧接着开场白，向用户抛出一个关于"此时此地情感、心境、处境"的开放式问题。
问题必须是无法通过搜索引擎获得标准答案的（例如探讨离别、思乡、忧乐、山水寄托）。

要求：
- 总字数严格控制在 150 字以内
- 必须且只能以问题的形式作为整段话的结尾
- 使用半文言文风格"""


def build_answer_prompt(character_name: str, user_answer: str) -> str:
    """构建生成赠语阶段的用户提示词"""
    return f"""你刚才向后生抛出了关于心境的提问，后生经过深思熟虑，给出了以下作答：
"{user_answer}"

请根据后生的主观情感（如孤独、迷茫、思乡、乐观等），撰写一段抚慰、共鸣并能赋予其力量的个性化赠语。

要求：
- 字数严格限制在 80 字以内
- 必须自然融入你自身的历史经历、典故或诗词名句来回应对方
- 严禁出现任何现代互联网或计算机术语（如"系统"、"徽章"、"解锁"）"""


